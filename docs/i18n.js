const STORAGE_KEY = 'ffmpeg-builder-lang';
const FALLBACK = 'en';
let current = FALLBACK;

function isSupported(id) {
  return LANGUAGES.some((language) => language.id === id);
}

// Saved choice first, then the browser languages, then English.
export function detectLanguage() {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (isSupported(saved)) return saved;
  } catch {
    // Storage may be unavailable; fall through to the browser languages.
  }
  for (const tag of navigator.languages || [navigator.language]) {
    const lower = String(tag || '').toLowerCase();
    if (lower.startsWith('zh')) return 'zh-CN';
    if (lower.startsWith('ja')) return 'ja';
    if (lower.startsWith('en')) return 'en';
  }
  return FALLBACK;
}

export function setLanguage(id) {
  current = isSupported(id) ? id : FALLBACK;
  document.documentElement.lang = current;
  try {
    localStorage.setItem(STORAGE_KEY, current);
  } catch {
    // Not persisted; the page still switches.
  }
}

export function getLanguage() {
  return LANGUAGES.find((language) => language.id === current);
}

export function t(key, vars = {}) {
  const text = MESSAGES[current][key] ?? MESSAGES[FALLBACK][key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? ''));
}

// Apply translations to elements marked with data-i18n (text), data-i18n-html
// (trusted markup from this file), data-i18n-placeholder and data-i18n-aria-label.
export function translateStatic(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((node) => { node.textContent = t(node.dataset.i18n); });
  root.querySelectorAll('[data-i18n-html]').forEach((node) => { node.innerHTML = t(node.dataset.i18nHtml); });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((node) => { node.placeholder = t(node.dataset.i18nPlaceholder); });
  root.querySelectorAll('[data-i18n-aria-label]').forEach((node) => { node.setAttribute('aria-label', t(node.dataset.i18nAriaLabel)); });
  document.title = t('page.title');
}
